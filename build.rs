// The merge `src/common` uses at runtime, so the build-time table and
// `/metrics/descriptions` merge a name's series the same way. The table
// covers every platform's stats.rs, the registry only this build's.
#[path = "src/common/description_merge.rs"]
mod description_merge;

fn main() {
    metric_descriptions::generate();

    #[cfg(target_os = "linux")]
    bpf::generate();
}

/// Extracts `name` and `description` from `#[metric(...)]` attributes in all
/// `stats.rs` files under `src/agent/samplers/`. Writes a static lookup table
/// to `$OUT_DIR/metric_descriptions.rs` so descriptions are available on every
/// platform regardless of which samplers are linked in.
mod metric_descriptions {
    use super::description_merge;
    use std::collections::BTreeMap;
    use std::io::Write;

    /// Each name's series: their static metadata and description.
    type Series = BTreeMap<String, Vec<description_merge::Series>>;

    pub fn generate() {
        let out_dir = std::env::var("OUT_DIR").unwrap();
        let dest = std::path::Path::new(&out_dir).join("metric_descriptions.rs");

        let mut series: Series = BTreeMap::new();

        // Walk all stats.rs files under src/agent/samplers/
        for entry in glob("src/agent/samplers/**/stats.rs") {
            let content = std::fs::read_to_string(&entry).unwrap_or_default();
            parse_metric_attrs(&content, &mut series);
            println!("cargo:rerun-if-changed={}", entry.display());
        }
        println!("cargo:rerun-if-changed=src/common/description_merge.rs");
        let descriptions: BTreeMap<String, String> = series
            .into_iter()
            .filter_map(|(name, s)| description_merge::merge(&s).map(|d| (name, d)))
            .collect();

        let mut out = std::fs::File::create(&dest).unwrap();
        writeln!(out, "/// Auto-generated by build.rs — do not edit.").unwrap();
        writeln!(
            out,
            "pub fn static_metric_descriptions() -> &'static [(&'static str, &'static str)] {{"
        )
        .unwrap();
        writeln!(out, "    &[").unwrap();
        for (name, desc) in &descriptions {
            // Escape any quotes in descriptions
            let escaped = desc.replace('\\', "\\\\").replace('"', "\\\"");
            writeln!(out, "        (\"{name}\", \"{escaped}\"),").unwrap();
        }
        writeln!(out, "    ]").unwrap();
        writeln!(out, "}}").unwrap();
    }

    /// Simple recursive glob for `**/stats.rs` patterns.
    fn glob(pattern: &str) -> Vec<std::path::PathBuf> {
        // pattern is like "src/agent/samplers/**/stats.rs"
        let parts: Vec<&str> = pattern.split("**/").collect();
        let base = std::path::Path::new(parts[0]);
        let filename = parts.get(1).unwrap_or(&"");
        let mut results = Vec::new();
        walk_dir(base, filename, &mut results);
        results.sort();
        results
    }

    fn walk_dir(dir: &std::path::Path, filename: &str, results: &mut Vec<std::path::PathBuf>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                walk_dir(&path, filename, results);
            } else if path.file_name().is_some_and(|n| n == filename) {
                results.push(path);
            }
        }
    }

    /// Parse `#[metric(name = "...", description = "...", metadata = { ... })]`
    /// from source text.
    fn parse_metric_attrs(src: &str, map: &mut Series) {
        let mut i = 0;
        let bytes = src.as_bytes();
        while i < bytes.len() {
            // Find #[metric(
            if let Some(pos) = src[i..].find("#[metric(") {
                let start = i + pos;
                // Find the closing )]
                if let Some(end_offset) = src[start..].find(")]") {
                    let block = &src[start..start + end_offset + 2];
                    let name = extract_string_field(block, "name");
                    let desc = extract_string_field(block, "description");
                    if let (Some(name), Some(desc)) = (name, desc) {
                        map.entry(name)
                            .or_default()
                            .push((extract_metadata(block), desc));
                    }
                    i = start + end_offset + 2;
                } else {
                    i = start + 9;
                }
            } else {
                break;
            }
        }
    }

    /// The string pairs of an attribute block's `metadata = { k = "v", ... }`.
    fn extract_metadata(block: &str) -> BTreeMap<String, String> {
        let mut out = BTreeMap::new();
        let Some(start) = block.find("metadata = {") else {
            return out;
        };
        let rest = &block[start + "metadata = {".len()..];
        let Some(end) = rest.find('}') else {
            return out;
        };
        for pair in rest[..end].split(',') {
            if let Some((k, v)) = pair.split_once('=') {
                let v = v.trim();
                if let Some(v) = v.strip_prefix('"').and_then(|v| v.strip_suffix('"')) {
                    out.insert(k.trim().to_string(), v.to_string());
                }
            }
        }
        out
    }

    /// Extract a string value for a field like `name = "value"` from an
    /// attribute block.
    /// The value is unescaped as the compiler reads it: `\"`, `\\`, `\n`,
    /// `\t`, and a `\` at the end of a line, which drops the line break and
    /// the next line's leading whitespace.
    fn extract_string_field(block: &str, field: &str) -> Option<String> {
        let pattern = format!("{field} = \"");
        let start = block.find(&pattern)? + pattern.len();
        let mut value = String::new();
        let mut chars = block[start..].chars().peekable();
        while let Some(c) = chars.next() {
            match c {
                '"' => return Some(value),
                '\\' => match chars.next()? {
                    'n' => value.push('\n'),
                    't' => value.push('\t'),
                    '\n' => {
                        while chars.peek().is_some_and(|c| c.is_whitespace()) {
                            chars.next();
                        }
                    }
                    other => value.push(other),
                },
                c => value.push(c),
            }
        }
        None
    }
}

#[cfg(target_os = "linux")]
mod bpf {
    use libbpf_cargo::SkeletonBuilder;

    // `SOURCES` lists all BPF programs and the sampler that contains them.
    // Each entry `(sampler, program)` maps to a unique path in the `samplers`
    // directory.
    const SOURCES: &[(&str, &str)] = &[
        ("blockio", "blockio"),
        ("cpu", "bandwidth"),
        ("cpu", "perf"),
        ("cpu", "tlb_flush"),
        ("cpu", "usage"),
        ("ext4", "alloc"),
        ("ext4", "journal"),
        ("ext4", "ops"),
        ("memory", "pagecache"),
        ("memory", "writeback"),
        ("network", "interfaces"),
        ("network", "traffic"),
        ("scheduler", "scheduler"),
        ("syscall", "syscall"),
        ("tcp", "connect_latency"),
        ("tcp", "packet_latency"),
        ("tcp", "receive"),
        ("tcp", "retransmit"),
        ("tcp", "traffic"),
        ("xfs", "log"),
    ];

    pub fn generate() {
        let out_dir = std::env::var("OUT_DIR").unwrap();
        let target_arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap();

        for (sampler, prog) in SOURCES {
            let src = format!("src/agent/samplers/{sampler}/linux/{prog}/mod.bpf.c");
            let tgt = format!("{out_dir}/{sampler}_{prog}.bpf.rs");

            if target_arch == "x86_64" {
                SkeletonBuilder::new()
                    .source(&src)
                    .clang_args([
                        "-Isrc/agent/bpf/x86_64",
                        "-fno-unwind-tables",
                        "-D__TARGET_ARCH_x86",
                        "-Wall",
                        "-Werror",
                    ])
                    .build_and_generate(&tgt)
                    .unwrap();
            } else if target_arch == "aarch64" {
                SkeletonBuilder::new()
                    .source(&src)
                    .clang_args([
                        "-Isrc/agent/bpf/aarch64",
                        "-fno-unwind-tables",
                        "-D__TARGET_ARCH_arm64",
                        "-Wall",
                        "-Werror",
                    ])
                    .build_and_generate(&tgt)
                    .unwrap();
            } else {
                panic!("BPF support only available for x86_64 and aarch64 architectures");
            }

            println!("cargo:rerun-if-changed={src}");
        }

        println!("cargo:rerun-if-changed=src/agent/bpf/histogram.h");
        println!("cargo:rerun-if-changed=src/agent/bpf/filesystem.h");
        println!("cargo:rerun-if-changed=src/agent/bpf/vmlinux.h");
    }
}
